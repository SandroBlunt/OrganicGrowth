/** Escapes a value for embedding as a single-quoted SQL string literal. None of this schema's own
 *  vocabulary/platform/slug values contain a quote today, but every embedding goes through this so a
 *  future value safely can. */
function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** Renders a `(v1, v2, ...)` SQL list for a `CHECK (col IN (...))` / `REFERENCES` seed clause. */
function sqlList(values: readonly string[]): string {
  return `(${values.map(sqlString).join(", ")})`;
}

