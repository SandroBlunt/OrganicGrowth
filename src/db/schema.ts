/**
 * The SQLite schema — one migration runner's worth of DDL for the local, in-process database ADR-0029
 * lands (issue #201, epic #195).
 *
 * A pure, deterministic deep module: it builds SQL TEXT (no disk, no network, no clock, no open
 * `DatabaseSync` handle) so it can be unit-tested on its own and reused unchanged by `migrate.ts`'s
 * orchestration shell. Nothing here talks to the filesystem or opens a connection — `connection.ts`
 * and `migrate.ts` do that.
 *
 * ## Covers every entity CONTEXT.md names (AC5, epic #195's schema section)
 *
 * `brand`, `channel`, `format`, `baseline_prompt`, `brand_asset` (tenancy/config); `run`, `trend`,
 * `idea`, `idea_recipe`, `asset`, `asset_media`, `copy_variant`, `job`, `gate_request` (the work);
 * `post`, `metric_snapshot`, `performance_score`, `channel_baseline` (the feedback loop). Every table
 * carries `id` (a stable surrogate id, TEXT — generated by the caller via `crypto.randomUUID()`,
 * mirroring `src/camera-hub/library.ts`'s existing convention; SQLite has no native UUID type),
 * `created_at`, `updated_at` (ISO-8601 strings) and `schema_version` (an INTEGER, defaulting to this
 * migration's own version — the version stamp no file in this repo has ever carried, and could never be
 * backfilled onto: "No file carries a version stamp, `updated_at`, or an etag" — epic #195's problem
 * statement). Read literally: an entity table's `schema_version` DEFAULT is baked into the `CREATE
 * TABLE` statement of whichever migration actually defined that table's shape — NOT necessarily
 * `CURRENT_SCHEMA_VERSION` (the highest version among ALL `MIGRATIONS`, structural or not). SQLite has
 * no `ALTER COLUMN ... SET DEFAULT`, so a later migration that never touches a given entity table's DDL
 * (like migration 2, issue #219, which only seeds `hook_type_vocabulary`/`theme_vocabulary`) leaves that
 * table's own DEFAULT exactly as its defining migration set it. The two numbers happened to be equal
 * while only one migration existed; migration 2 is the first case where they diverge.
 *
 * ## Closed vocabularies are REFERENCE TABLES, not just CHECK constraints
 *
 * `hook_type_vocabulary` and `theme_vocabulary` are seeded, at migration time, from
 * `src/vocabulary/hook-type.ts`'s `HOOK_TYPES` and `src/vocabulary/theme.ts`'s `THEMES` — the SAME
 * arrays `CONTEXT.md`'s glossary entries are asserted against (`context-md.docs-test.ts`). `idea.hook_type`
 * / `idea.theme` are real FOREIGN KEYs into those tables, enforced by `PRAGMA foreign_keys = ON`
 * (`connection.ts`) — not merely a static CHECK list that could silently diverge from the TypeScript
 * source. `recipe_vocabulary` does the identical thing for `src/recipe/registry.ts`'s
 * `listWiredRecipeSlugs()` (AC7: "trust the registry, not CONTEXT.md's count of two" — the registry IS
 * the seed source, so there is nothing left to trust separately). Widening any of these three sets is a
 * NEW migration (an `INSERT` for the new row(s)), never an edit to this migration's already-shipped SQL
 * — proven out by migration 2 (issue #219), which adds ONLY the `unclassified` row to
 * `hook_type_vocabulary`/`theme_vocabulary`, on top of migration 1's already-shipped ten/nine.
 *
 * `channel.platform` / `trend.platform` use a plain CHECK against `KNOWN_PLATFORMS`
 * (`src/copy/platform-shape.ts`) — that list is already a live, tested constant elsewhere in this
 * codebase and is smaller-stakes than the two vocabularies this issue exists to close, so a reference
 * table would be ceremony without benefit. `format.cadence` / `run.cadence` (`'weekly'|'daily'`,
 * ADR-0022) and `format.source_mode` (`'peer'|'curated'`, ADR-0013) are likewise plain CHECKs, mirroring
 * `src/format/store.ts`'s existing `FormatCadence`/`FormatSourceMode` TS union types (kept in sync by
 * hand — both are two-value sets fixed by an already-decided ADR, not open-ended).
 *
 * ## What this migration deliberately does NOT build
 *
 * `account`, `user`, `connection` — the epic's own "leave room, don't build" instruction (AC12). No
 * column here reshapes if/when they arrive: a future migration adds those three tables plus an
 * OPTIONAL `account_id` column on `brand` (SQLite's `ALTER TABLE ... ADD COLUMN` supports a nullable
 * addition without a table rebuild). See `docs/adr/0029` for the full reasoning.
 */

